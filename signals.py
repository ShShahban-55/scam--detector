import re

def norm(t: str) -> str:
    t = re.sub(r"[ً-ٟـ]", "", t)                       # تشكيل وتطويل
    t = t.translate(str.maketrans({"أ": "ا", "إ": "ا", "آ": "ا", "ى": "ي", "ة": "ه",
                                   "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
                                   "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9"}))
    return t.lower()

