_COMPILED = [(k, label, w, [re.compile(norm(p)) for p in pats]) for k, label, w, pats in RULES]
_POS = [(re.compile(norm(p)), label, w) for p, label, w in POSITIVE]

def detect(text: str) -> dict:
    t = norm(text)
    matched = []
    for key, label, w, pats in _COMPILED:
        if any(p.search(t) for p in pats):
            matched.append({"key": key, "label": label, "weight": w})
    positives = [{"label": label, "weight": w} for p, label, w in _POS if p.search(t)]
    score = sum(m["weight"] for m in matched)
    if positives and any(m["key"] == "credentials" for m in matched):
        score += sum(p["weight"] for p in positives)
    else:
        positives = []
    return {"matched": matched, "positives": positives, "score": max(0, min(100, score))}

def verdict_from_score(score: int) -> str:
    return "نصب" if score >= 70 else "مشبوه" if score >= 35 else "سليم"

